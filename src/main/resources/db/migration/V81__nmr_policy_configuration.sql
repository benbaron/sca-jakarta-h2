-- Configuration evidence only. No defaults, seed rates or accounting writes.
CREATE TABLE IF NOT EXISTS nmr_policy_version
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portable_id UUID NOT NULL UNIQUE,
    company_id BIGINT NOT NULL REFERENCES company(id),
    request_hash VARCHAR(64) NOT NULL,
    saved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    saved_by VARCHAR(200) NOT NULL,
    policy_code VARCHAR(60) NOT NULL,
    category VARCHAR(80) NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE,
    rate NUMERIC(19,4) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    date_basis VARCHAR(200) NOT NULL,
    rounding_rule VARCHAR(200) NOT NULL,
    eligibility VARCHAR(1000) NOT NULL,
    exemptions VARCHAR(1000) NOT NULL,
    recipient VARCHAR(300) NOT NULL,
    reporting VARCHAR(500) NOT NULL,
    merchant_path VARCHAR(1000) NOT NULL,
    source_reference VARCHAR(500) NOT NULL,
    authority VARCHAR(200) NOT NULL,
    source_date DATE NOT NULL,
    CONSTRAINT uq_nmr_policy_interval_start UNIQUE(company_id, policy_code, category, valid_from),
    CONSTRAINT ck_nmr_policy_dates CHECK(valid_to IS NULL OR valid_to >= valid_from),
    CONSTRAINT ck_nmr_policy_rate CHECK(rate >= 0),
    CONSTRAINT ck_nmr_policy_identity CHECK(length(trim(policy_code)) > 0 AND length(trim(category)) > 0),
    CONSTRAINT ck_nmr_policy_source CHECK(length(trim(source_reference)) > 0 AND length(trim(authority)) > 0),
    CONSTRAINT ck_nmr_policy_currency CHECK(length(currency) = 3)
);
CREATE INDEX IF NOT EXISTS ix_nmr_policy_company ON nmr_policy_version(company_id, policy_code, category, valid_from);
