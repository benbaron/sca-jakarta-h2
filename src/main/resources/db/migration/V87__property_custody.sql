ALTER TABLE inventory_item ADD COLUMN IF NOT EXISTS financial_treatment VARCHAR(40) DEFAULT 'CAPITALIZED_INVENTORY' NOT NULL;
ALTER TABLE inventory_item ADD CONSTRAINT IF NOT EXISTS ck_inventory_financial_treatment
    CHECK (financial_treatment IN ('CAPITALIZED_INVENTORY', 'EXPENSED_SUPPLY'));

CREATE TABLE IF NOT EXISTS property_custody_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portable_id UUID NOT NULL UNIQUE,
    company_id BIGINT NOT NULL,
    fixed_asset_id BIGINT,
    inventory_item_id BIGINT,
    event_type VARCHAR(24) NOT NULL,
    event_date DATE NOT NULL,
    quantity DECIMAL(19,4) NOT NULL,
    guardian_name VARCHAR(200), guardian_email VARCHAR(254), guardian_phone VARCHAR(80),
    location VARCHAR(200), item_condition VARCHAR(40) NOT NULL,
    confirmation_status VARCHAR(24) NOT NULL,
    confirmation_due_date DATE, confirmation_date DATE, expected_return_date DATE,
    removal_reason VARCHAR(500), external_authorization_reference VARCHAR(200),
    notes CLOB, actor VARCHAR(200) NOT NULL,
    correction_of_event_id BIGINT UNIQUE,
    fixed_asset_lifecycle_event_id BIGINT,
    inventory_movement_id BIGINT,
    accounting_treatment VARCHAR(40) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_property_custody_company FOREIGN KEY (company_id) REFERENCES company(id),
    CONSTRAINT fk_property_custody_asset FOREIGN KEY (fixed_asset_id) REFERENCES fixed_asset(id),
    CONSTRAINT fk_property_custody_inventory FOREIGN KEY (inventory_item_id) REFERENCES inventory_item(id),
    CONSTRAINT fk_property_custody_correction FOREIGN KEY (correction_of_event_id) REFERENCES property_custody_event(id),
    CONSTRAINT fk_property_custody_lifecycle FOREIGN KEY (fixed_asset_lifecycle_event_id) REFERENCES fixed_asset_lifecycle_event(id),
    CONSTRAINT fk_property_custody_movement FOREIGN KEY (inventory_movement_id) REFERENCES inventory_movement(id),
    CONSTRAINT ck_property_custody_subject CHECK ((fixed_asset_id IS NULL) <> (inventory_item_id IS NULL)),
    CONSTRAINT ck_property_custody_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_property_custody_type CHECK (event_type IN ('ASSIGNMENT','CONFIRMATION','LOAN','RETURN','TRANSFER','REMOVAL')),
    CONSTRAINT ck_property_custody_confirmation CHECK (confirmation_status IN ('NOT_REQUIRED','PENDING','CONFIRMED','EXCEPTION')),
    CONSTRAINT ck_property_custody_accounting CHECK (accounting_treatment IN ('CUSTODY_ONLY','FIXED_ASSET_LIFECYCLE','INVENTORY_MOVEMENT','EXPENSED_NO_VALUE'))
);
CREATE INDEX IF NOT EXISTS ix_property_custody_company_date ON property_custody_event(company_id,event_date);
CREATE INDEX IF NOT EXISTS ix_property_custody_fixed_asset ON property_custody_event(fixed_asset_id,event_date);
CREATE INDEX IF NOT EXISTS ix_property_custody_inventory ON property_custody_event(inventory_item_id,event_date);
